CREATE TABLE IF NOT EXISTS events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, tenant VARCHAR(48) NOT NULL,
 scope_hash CHAR(64) NOT NULL, kind VARCHAR(48) NOT NULL,
 object_ref CHAR(64) NOT NULL, outcome VARCHAR(32) NOT NULL,
 duration_us BIGINT UNSIGNED, recorded DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 KEY (tenant,id), KEY (scope_hash,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
